'use strict';














const fs = require('fs');
const path = require('path');
const { buildSpeciesIdMap } = require('./lib/species-ids');
const { ordered, poolAndCatalog } = require('./lib/id-registry');

const OUT_DIR = path.join(__dirname, 'out');
const ENGINE_DATA_SRC = path.join(__dirname, '..', '..', 'crates', 'engine-data', 'src');

function rustIdent(name) {
	return name.toUpperCase().replace(/[^A-Z0-9]/g, '');
}

function main() {
	const items = ordered('items', poolAndCatalog('items'));
	const { byName: speciesByName } = buildSpeciesIdMap();


	const idConsts = items.map((it, i) => `    pub const ${rustIdent(it.id)}: ItemId = ${i + 1};`);
	const names = items.map(it => `    "${it.name}",`);

	const megaStoneRows = [];
	items.forEach((it, i) => {
		if (!it.megaStone) return;
		const itemId = i + 1;
		for (const [baseName, megaName] of Object.entries(it.megaStone)) {
			const baseId = speciesByName.get(baseName);
			const megaId = speciesByName.get(megaName);
			if (baseId === undefined) throw new Error(`${it.id}: megaStone base species "${baseName}" not in species.json`);
			if (megaId === undefined) throw new Error(`${it.id}: megaStone target species "${megaName}" not in species.json`);
			megaStoneRows.push(`    (item_ids::${rustIdent(it.id)}, ${baseId}, ${megaId}), // ${it.id}: ${baseName} -> ${megaName}`);
		}
	});


	const flingPower = items.map(it => (it.fling ? it.fling.basePower : 0));
	const naturalGift = items.map(it => (it.naturalGift ? `Some((Type::${it.naturalGift.type}, ${it.naturalGift.basePower}))` : 'None'));


	const gen5ById = new Map(require(path.join(__dirname, 'out', 'vgc13', 'items.json')).map(g => [g.id, g]));
	const gen5Of = it => gen5ById.get(it.id) || it;
	const flingPowerGen5 = items.map(it => (gen5Of(it).fling ? gen5Of(it).fling.basePower : 0));
	const naturalGiftGen5 = items.map(it => {
		const g = gen5Of(it);
		return g.naturalGift ? `Some((Type::${g.naturalGift.type}, ${g.naturalGift.basePower}))` : 'None';
	});


	const genPool = (dirs, kind) => {
		const m = new Map();
		for (const d of dirs) {
			for (const e of require(path.join(__dirname, 'out', d, `${kind}.json`))) if (!m.has(e.id)) m.set(e.id, e);
		}
		return m;
	};
	const flingOf = byId => items.map(it => { const g = byId.get(it.id) || it; return g.fling ? g.fling.basePower : 0; });
	const naturalGiftOf = byId => items.map(it => {
		const g = byId.get(it.id) || it;
		return g.naturalGift ? `Some((Type::${g.naturalGift.type}, ${g.naturalGift.basePower}))` : 'None';
	});
	const gen6ById = genPool(['vgc16', 'vgc15', 'vgc14'], 'items');
	const flingPowerGen6 = flingOf(gen6ById);
	const naturalGiftGen6 = naturalGiftOf(gen6ById);

	const gen7ById = genPool(['vgc19', 'vgc18', 'vgc17'], 'items');
	const flingPowerGen7 = flingOf(gen7ById);
	const naturalGiftGen7 = naturalGiftOf(gen7ById);

	const rust = `//! Generated by tools/gen-data/codegen-items.js from tools/gen-data/out/items.json.
//! DO NOT EDIT BY HAND. Regenerate after any Showdown pin bump (SHOWDOWN_PIN.md) or legal-pool
//! change. See that script's header comment for scope (ids/names + the Mega Evolution trigger
//! table, and Fling / Natural Gift's per-item power and type).

use crate::species_table::SpeciesId;
use crate::type_chart::Type;

pub type ItemId = u16;

pub const ITEM_COUNT: usize = ${items.length};

/// Fixed ids (index + 1 into \`ITEM_NAMES\`; 0 is NONE_ID).
pub mod item_ids {
    use super::ItemId;
${idConsts.join('\n')}
}

pub const ITEM_NAMES: [&str; ITEM_COUNT] = [
${names.join('\n')}
];

pub fn name(id: ItemId) -> &'static str {
    ITEM_NAMES[(id - 1) as usize]
}

/// Fling's base power for the item (\`item.fling.basePower\`); 0 = it can't be flung. Index = id - 1.
pub const FLING_POWER: [u8; ITEM_COUNT] = [${flingPower.join(', ')}];

/// Natural Gift's type and base power for a berry (\`item.naturalGift\`). Index = id - 1.
pub const NATURAL_GIFT: [Option<(Type, u8)>; ITEM_COUNT] = [
${naturalGift.map(x => `    ${x},`).join('\n')}
];

/// Gen 5's Fling powers and Natural Gift (the gen5 mod), indexed like [\`FLING_POWER\`] / [\`NATURAL_GIFT\`] (\`Rules\`).
pub const FLING_POWER_GEN5: [u8; ITEM_COUNT] = [${flingPowerGen5.join(', ')}];
pub const NATURAL_GIFT_GEN5: [Option<(Type, u8)>; ITEM_COUNT] = [
${naturalGiftGen5.map(x => `    ${x},`).join('\n')}
];
/// Gen 6's (the gen6 mod), indexed like [\`FLING_POWER\`] / [\`NATURAL_GIFT\`].
pub const FLING_POWER_GEN6: [u8; ITEM_COUNT] = [${flingPowerGen6.join(', ')}];
pub const NATURAL_GIFT_GEN6: [Option<(Type, u8)>; ITEM_COUNT] = [
${naturalGiftGen6.map(x => `    ${x},`).join('\n')}
];
/// Gen 7's (the gen7 mod), indexed like [\`FLING_POWER\`] / [\`NATURAL_GIFT\`].
pub const FLING_POWER_GEN7: [u8; ITEM_COUNT] = [${flingPowerGen7.join(', ')}];
pub const NATURAL_GIFT_GEN7: [Option<(Type, u8)>; ITEM_COUNT] = [
${naturalGiftGen7.map(x => `    ${x},`).join('\n')}
];

/// \`(mega stone item, required current species, resulting mega species)\`. Mirrors Showdown's own
/// \`canMegaEvo\` check exactly (one row per entry in the pinned repo's \`data/items.ts\` \`megaStone\`
/// maps) - including the one case where the "required current species" isn't the mega forme's
/// plain base species (Floette: the stone requires the \`Floette-Eternal\` forme specifically, not
/// base \`Floette\`).
pub const MEGA_STONES: &[(ItemId, SpeciesId, SpeciesId)] = &[
${megaStoneRows.join('\n')}
];

/// The mega forme \`current_species\` becomes if holding \`item\`, or \`None\` if \`item\` isn't a mega
/// stone for that species. Linear scan over ${megaStoneRows.length} rows - not a hot path (checked
/// at most twice per turn, once per side, only when that side's chosen action requests a mega
/// evolution).
pub fn mega_forme_for(item: ItemId, current_species: SpeciesId) -> Option<SpeciesId> {
    MEGA_STONES.iter().find(|&&(i, s, _)| i == item && s == current_species).map(|&(_, _, m)| m)
}
`;

	fs.mkdirSync(ENGINE_DATA_SRC, { recursive: true });
	fs.writeFileSync(path.join(ENGINE_DATA_SRC, 'items_table.rs'), rust);
	console.log(`wrote ${ENGINE_DATA_SRC}\\items_table.rs (${items.length} items, ${megaStoneRows.length} mega stones)`);
}

main();
