'use strict';











const fs = require('fs');
const path = require('path');

const OUT_DIR = path.join(__dirname, 'out');
const ENGINE_DATA_SRC = path.join(__dirname, '..', '..', 'crates', 'engine-data', 'src');

function main() {
	const types = require(path.join(OUT_DIR, 'types.json'));
	const ids = types.map(t => t.id);
	const idSet = new Set(ids);

	const variantName = id => id === 'stellar' ? 'Stellar' : id.charAt(0).toUpperCase() + id.slice(1);

	const chartRows = types.map(defender => {
		const row = ids.map(attackerId => {
			const code = defender.damageTaken[types.find(t => t.id === attackerId).name];
			return code ?? 0;
		});
		return `    [${row.join(', ')}], // ${defender.id} takes from [${ids.join(', ')}]`;
	});



	const gen5Types = require(path.join(OUT_DIR, 'vgc13', 'types.json'));
	const gen5Rows = types.map(defender => {
		const g = gen5Types.find(t => t.id === defender.id);
		const row = ids.map(attackerId => (g ? g.damageTaken[types.find(t => t.id === attackerId).name] : 0) ?? 0);
		return `    [${row.join(', ')}], // ${defender.id}`;
	});



	const chartOf = dir => {
		const genTypes = require(path.join(OUT_DIR, dir, 'types.json'));
		return types.map(defender => {
			const g = genTypes.find(t => t.id === defender.id);
			const row = ids.map(attackerId => (g ? g.damageTaken[types.find(t => t.id === attackerId).name] : 0) ?? 0);
			return `    [${row.join(', ')}], // ${defender.id}`;
		});
	};
	const gen6Rows = chartOf('vgc16');

	const gen7Rows = chartOf('vgc19');

	const rust = `//! Generated by tools/gen-data/codegen-types.js from tools/gen-data/out/types.json.
//! DO NOT EDIT BY HAND. Regenerate after any Showdown pin bump (SHOWDOWN_PIN.md).

/// One of the ${ids.length} damage types (design.md §5, §9). Order is fixed (alphabetical, as
/// extracted) and used directly as an index into \`TYPE_CHART\` - do not reorder without
/// regenerating.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Hash)]
#[repr(u8)]
pub enum Type {
${ids.map((id, i) => `    ${variantName(id)} = ${i},`).join('\n')}
}

pub const TYPE_COUNT: usize = ${ids.length};

impl Type {
    pub const ALL: [Type; TYPE_COUNT] = [
${ids.map(id => `        Type::${variantName(id)},`).join('\n')}
    ];

    pub fn from_index(i: u8) -> Type {
        Type::ALL[i as usize]
    }
}

/// Raw Showdown effectiveness codes: \`TYPE_CHART[defending as usize][attacking as usize]\`.
/// 0 = normal, 1 = super-effective, 2 = resisted, 3 = immune. See \`effectiveness_code\` /
/// \`stage_for\` in engine-core's damage module for how these combine across a mon's two types.
pub const TYPE_CHART: [[u8; TYPE_COUNT]; TYPE_COUNT] = [
${chartRows.join('\n')}
];

pub fn effectiveness_code(attacking: Type, defending: Type) -> u8 {
    TYPE_CHART[defending as usize][attacking as usize]
}

/// Gen 5's chart (the gen5 mod), indexed like [\`TYPE_CHART\`]: no Fairy (its row and column neutral), Steel resists Ghost and Dark.
pub const TYPE_CHART_GEN5: [[u8; TYPE_COUNT]; TYPE_COUNT] = [
${gen5Rows.join('\n')}
];

/// Gen 6's chart (the gen6 mod), indexed like [\`TYPE_CHART\`].
pub const TYPE_CHART_GEN6: [[u8; TYPE_COUNT]; TYPE_COUNT] = [
${gen6Rows.join('\n')}
];

/// Gen 7's chart (the gen7 mod), indexed like [\`TYPE_CHART\`].
pub const TYPE_CHART_GEN7: [[u8; TYPE_COUNT]; TYPE_COUNT] = [
${gen7Rows.join('\n')}
];
`;

	fs.mkdirSync(ENGINE_DATA_SRC, { recursive: true });
	fs.writeFileSync(path.join(ENGINE_DATA_SRC, 'type_chart.rs'), rust);
	console.log(`wrote ${ENGINE_DATA_SRC}\\type_chart.rs (${ids.length} types)`);


	for (const t of types) {
		for (const key of Object.keys(t.damageTaken)) {
			const id = key.toLowerCase();
			if (!idSet.has(id) && !['brn', 'par', 'frz', 'slp', 'psn'].includes(key)) {

				if (!idSet.has(id)) console.warn(`note: unrecognized damageTaken key "${key}" on ${t.id}`);
			}
		}
	}
}

main();
