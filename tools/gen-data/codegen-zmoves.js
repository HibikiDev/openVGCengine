'use strict';











const fs = require('fs');
const path = require('path');
const { Dex } = require('./lib/showdown');
const { buildSpeciesIdMap } = require('./lib/species-ids');

const ENGINE_DATA_SRC = path.join(__dirname, '..', '..', 'crates', 'engine-data', 'src');
const registry = kind => JSON.parse(fs.readFileSync(path.join(__dirname, 'ids', `${kind}.json`), 'utf8'));

function main() {
	const dex = Dex.mod('gen7');
	const moveIds = registry('moves');
	const itemIds = registry('items');
	const moveId = id => {
		const i = moveIds.indexOf(id);
		if (i < 0) throw new Error(`move ${id} has no registry id`);
		return i + 1;
	};
	const itemId = id => {
		const i = itemIds.indexOf(id);
		if (i < 0) throw new Error(`item ${id} has no registry id`);
		return i + 1;
	};
	const { byShowdownId } = buildSpeciesIdMap();
	const speciesId = name => {
		const id = byShowdownId.get(dex.species.get(name).id);
		if (!id) throw new Error(`species ${name} has no engine id`);
		return id;
	};
	const BOOSTS = ['atk', 'def', 'spa', 'spd', 'spe', 'accuracy', 'evasion'];
	const EFFECTS = { heal: 'Heal', healreplacement: 'HealReplacement', clearnegativeboost: 'ClearNegativeBoost', redirect: 'Redirect',
		crit2: 'Crit2', curse: 'Curse' };


	const rows = moveIds.map(id => {
		const m = dex.moves.get(id);
		const z = m.exists && m.gen <= 7 ? m.zMove : undefined;
		const power = z && z.basePower ? z.basePower : 0;
		if (power > 255) throw new Error(`${id}: Z power ${power} does not fit a u8`);
		let effect = 'ZEffect::None';
		if (z && z.boost) effect = `ZEffect::Boost([${BOOSTS.map(b => z.boost[b] || 0).join(', ')}])`;
		else if (z && z.effect) {
			if (!EFFECTS[z.effect]) throw new Error(`${id}: unknown Z effect ${z.effect}`);
			effect = `ZEffect::${EFFECTS[z.effect]}`;
		}
		return `    ZMove { power: ${power}, effect: ${effect} }, // ${id}`;
	});


	const crystals = dex.items.all().filter(it => it.zMove && it.gen <= 7).sort((a, b) => itemId(a.id) - itemId(b.id));
	const typeName = t => t;
	const typeZ = {};
	const crystalRows = crystals.map(it => {
		if (it.zMoveFrom) {
			const users = (it.itemUser || []).map(speciesId);
			return `    (${itemId(it.id)}, Crystal::Signature { base_move: ${moveId(dex.moves.get(it.zMoveFrom).id)}, z_move: ${moveId(dex.moves.get(it.zMove).id)}, users: &[${users.join(', ')}] }), // ${it.id}`;
		}
		const zMove = dex.moves.all().find(m => m.isZ === it.id);
		if (!zMove) throw new Error(`${it.id}: no Z-Move has isZ = ${it.id}`);
		typeZ[it.zMoveType] = moveId(zMove.id);
		return `    (${itemId(it.id)}, Crystal::Type(Type::${typeName(it.zMoveType)})), // ${it.id}`;
	});
	const types = dex.types.names().filter(t => t !== 'Stellar');
	const typeZRows = types.map(t => `    (Type::${t}, ${typeZ[t] || 0}),`);
	if (types.some(t => !typeZ[t])) throw new Error(`a type without its Z-Move: ${types.filter(t => !typeZ[t]).join(', ')}`);

	const rust = `//! Generated by tools/gen-data/codegen-zmoves.js from the gen7 mod. DO NOT EDIT BY HAND.
//! Gen 7's Z-Moves: each move's \`zMove\` data, each type's damaging Z-Move, the
//! Z-Crystals. Regenerate after a Showdown pin bump.

use crate::items_table::ItemId;
use crate::moves_table::{MoveId, MOVE_COUNT};
use crate::species_table::SpeciesId;
use crate::type_chart::Type;

/// A status move's Z effect (\`move.zMove.boost\` / \`.effect\`, \`runZPower\`), before the move itself runs.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum ZEffect {
    None,
    /// Stat stages for the user, \`[atk, def, spa, spd, spe, accuracy, evasion]\`.
    Boost([i8; 7]),
    /// The user is fully healed (\`heal\`).
    Heal,
    /// The next mon into the user's slot is fully healed (\`healreplacement\`: Memento, Parting Shot).
    HealReplacement,
    /// The user's lowered stages are reset (\`clearnegativeboost\`).
    ClearNegativeBoost,
    /// The user becomes the center of attention (\`redirect\`: Follow Me's volatile).
    Redirect,
    /// The user's crit stage rises by 2 (\`crit2\`: Focus Energy's volatile).
    Crit2,
    /// Z-Curse: a Ghost user heals fully, any other gains +1 Attack.
    Curse,
}

/// One move's Z data: \`power\` = its damaging Z-Move's base power (\`zMove.basePower\`; 0 when it has none), \`effect\` = a status
/// move's Z effect.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct ZMove {
    pub power: u8,
    pub effect: ZEffect,
}

/// Indexed like \`moves_table::MOVES\` (id - 1).
pub const Z_MOVES: [ZMove; MOVE_COUNT] = [
${rows.join('\n')}
];

pub fn z_move(id: MoveId) -> ZMove {
    Z_MOVES[(id - 1) as usize]
}

/// A Z-Crystal: a type crystal turns every move of its type into that type's Z-Move (status moves into their Z version); a signature
/// crystal one move of its \`users\` into its own Z-Move (\`zMoveFrom\` -> \`zMove\`).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Crystal {
    Type(Type),
    Signature { base_move: MoveId, z_move: MoveId, users: &'static [SpeciesId] },
}

pub const Z_CRYSTALS: &[(ItemId, Crystal)] = &[
${crystalRows.join('\n')}
];

pub fn crystal(item: ItemId) -> Option<Crystal> {
    Z_CRYSTALS.iter().find(|&&(i, _)| i == item).map(|&(_, c)| c)
}

/// Each type's damaging Z-Move (\`BattleActions.Z_MOVES\`).
pub const TYPE_Z_MOVES: &[(Type, MoveId)] = &[
${typeZRows.join('\n')}
];

pub fn type_z_move(t: Type) -> MoveId {
    TYPE_Z_MOVES.iter().find(|&&(x, _)| x == t).map_or(0, |&(_, m)| m)
}
`;
	fs.writeFileSync(path.join(ENGINE_DATA_SRC, 'z_table.rs'), rust);
	console.log(`wrote z_table.rs: ${rows.filter(r => !r.includes('power: 0, effect: ZEffect::None')).length} moves with Z data, ${crystals.length} crystals`);
}

main();
