'use strict';











const fs = require('fs');
const path = require('path');
const { ordered, poolAndCatalog } = require('./lib/id-registry');

const OUT_DIR = path.join(__dirname, 'out');
const ENGINE_DATA_SRC = path.join(__dirname, '..', '..', 'crates', 'engine-data', 'src');

function rustIdent(name) {
	return name.toUpperCase().replace(/[^A-Z0-9]/g, '');
}


const FLAGS = ['breakable', 'cantsuppress', 'failroleplay', 'failskillswap', 'noentrain', 'noreceiver', 'notrace', 'notransform'];

function main() {
	const abilities = ordered('abilities', poolAndCatalog('abilities'));

	const idConsts = abilities.map((a, i) => `    pub const ${rustIdent(a.id)}: AbilityId = ${i + 1};`);
	const names = abilities.map(a => `    "${a.name}",`);
	const flags = abilities.map(a => {
		if (!a.flags) throw new Error(`${a.id}: no flags in the extract (rerun gen-data.js / catalog-data.js)`);
		for (const f of a.flags) if (!FLAGS.includes(f)) throw new Error(`${a.id}: unknown ability flag ${f}`);
		return `    0b${FLAGS.map(f => (a.flags.includes(f) ? '1' : '0')).reverse().join('')},`;
	});
	const flagConsts = FLAGS.map((f, i) => `    pub const ${f.toUpperCase()}: u8 = 1 << ${i};`);
	const bits = fl => FLAGS.reduce((b, f, i) => b | (fl.includes(f) ? 1 << i : 0), 0);


	const base = new Map(abilities.map((a, i) => [a.id, [i + 1, bits(a.flags)]]));
	const overrides = dirs => {
		const seen = new Map();
		for (const d of dirs) {
			const file = path.join(OUT_DIR, d, 'abilities.json');
			if (!fs.existsSync(file)) throw new Error(`${file} missing (gen-data.js --format ...)`);
			for (const a of JSON.parse(fs.readFileSync(file, 'utf8'))) {
				const b = base.get(a.id);
				if (b && a.flags && bits(a.flags) !== b[1]) seen.set(a.id, `    (${b[0]}, 0b${bits(a.flags).toString(2).padStart(8, '0')}), // ${a.id}`);
			}
		}
		return [...seen.values()];
	};
	const gen5 = overrides(['vgc13']);
	const gen6 = overrides(['vgc14', 'vgc15', 'vgc16']);
	const gen7 = overrides(['vgc17', 'vgc18', 'vgc19']);




	const modOverrides = mod => {
		const { Dex } = require('./lib/showdown');
		const dex = Dex.mod(mod);
		const rows = [];
		for (const [id, [n, b]] of base) {
			const a = dex.abilities.get(id);
			if (!a.exists) continue;
			const fl = Object.keys(a.flags || {}).filter(f => a.flags[f] && FLAGS.includes(f));
			if (bits(fl) !== b) rows.push(`    (${n}, 0b${bits(fl).toString(2).padStart(8, '0')}), // ${id}`);
		}
		return rows;
	};
	const gen9predlc = modOverrides('gen9predlc');

	const gen8 = modOverrides('gen8');

	const rust = `//! Generated by tools/gen-data/codegen-abilities.js from tools/gen-data/out/abilities.json.
//! DO NOT EDIT BY HAND. Regenerate after any Showdown pin bump (SHOWDOWN_PIN.md) or legal-pool
//! change.
//!
//! Ids, names and Showdown's ability flags; the effects live in engine-core.

pub type AbilityId = u16;

pub const ABILITY_COUNT: usize = ${abilities.length};

/// Fixed ids (index + 1 into \`ABILITY_NAMES\`; 0 is NONE_ID).
pub mod ability_ids {
    use super::AbilityId;
${idConsts.join('\n')}
}

pub const ABILITY_NAMES: [&str; ABILITY_COUNT] = [
${names.join('\n')}
];

pub fn name(id: AbilityId) -> &'static str {
    ABILITY_NAMES[(id - 1) as usize]
}

/// Showdown's ability flags (\`AbilityFlags\`), one bit each.
pub mod ability_flags {
${flagConsts.join('\n')}
}

/// Each ability's flags (index id - 1).
pub const ABILITY_FLAGS: [u8; ABILITY_COUNT] = [
${flags.join('\n')}
];

/// Whether \`id\` carries \`flag\` (an \`ability_flags\` bit); no ability (0) carries none.
pub const fn has_flag(id: AbilityId, flag: u8) -> bool {
    id != 0 && ABILITY_FLAGS[(id - 1) as usize] & flag != 0
}

/// The Gen 5 (\`gen5vgc2013\`) abilities whose flags differ from \`ABILITY_FLAGS\`: (id, that format's flags).
pub const ABILITY_FLAG_OVERRIDES_GEN5: &[(AbilityId, u8)] = &[
${gen5.join('\n')}
];

/// The Gen 6 (\`gen6vgc2014 / 15 / 16\`) abilities whose flags differ from \`ABILITY_FLAGS\`.
pub const ABILITY_FLAG_OVERRIDES_GEN6: &[(AbilityId, u8)] = &[
${gen6.join('\n')}
];

/// The Gen 7 (\`gen7vgc2017 / 18 / 19\`) abilities whose flags differ from \`ABILITY_FLAGS\`.
pub const ABILITY_FLAG_OVERRIDES_GEN7: &[(AbilityId, u8)] = &[
${gen7.join('\n')}
];

/// The Scarlet / Violet Reg C / D (\`gen9predlc\`) abilities whose flags differ from \`ABILITY_FLAGS\`.
pub const ABILITY_FLAG_OVERRIDES_GEN9_PREDLC: &[(AbilityId, u8)] = &[
${gen9predlc.join('\n')}
];

/// The Sword / Shield (\`gen8vgc2020 / 2021 / 2022\`, the gen8 mod) abilities whose flags differ from \`ABILITY_FLAGS\`.
pub const ABILITY_FLAG_OVERRIDES_GEN8: &[(AbilityId, u8)] = &[
${gen8.join('\n')}
];

/// \`has_flag\` under a format's overrides (\`Rules::ability_flag_overrides\`).
pub fn has_flag_in(overrides: &[(AbilityId, u8)], id: AbilityId, flag: u8) -> bool {
    match overrides.iter().find(|&&(o, _)| o == id) {
        Some(&(_, flags)) => flags & flag != 0,
        None => has_flag(id, flag),
    }
}
`;

	fs.mkdirSync(ENGINE_DATA_SRC, { recursive: true });
	fs.writeFileSync(path.join(ENGINE_DATA_SRC, 'abilities_table.rs'), rust);
	console.log(`wrote ${ENGINE_DATA_SRC}\\abilities_table.rs (${abilities.length} abilities)`);
}

main();
