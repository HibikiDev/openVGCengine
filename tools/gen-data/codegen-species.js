'use strict';

















const fs = require('fs');
const path = require('path');
const { buildSpeciesIdMap } = require('./lib/species-ids');
const { ordered, poolAndCatalog } = require('./lib/id-registry');

const ENGINE_DATA_SRC = path.join(__dirname, '..', '..', 'crates', 'engine-data', 'src');

const STAT_ORDER = ['hp', 'atk', 'def', 'spa', 'spd', 'spe'];



const ABILITY_SLOTS = ['0', '1', 'H', 'S'];

function typeVariant(name) {
	return name;
}

function abilityIdsFor(abilitiesByName, species) {
	return ABILITY_SLOTS.map(slot => {
		const name = species.abilities[slot];
		if (!name) return 0;
		const id = abilitiesByName.get(name);
		if (id === undefined) throw new Error(`${species.name}: ability "${name}" (slot ${slot}) not in abilities.json`);
		return id;
	});
}



function battleOnlyBase(s, byName) {
	if (!s.battleOnly) return 0;
	const name = Array.isArray(s.battleOnly) ? s.battleOnly[0] : s.battleOnly;
	return byName.get(name) || 0;
}

const GENDER = { '': 'Mixed', M: 'Male', F: 'Female', N: 'Genderless' };

function emitSpecies(s, abilityIds, byName) {
	if (!(s.gender in GENDER)) throw new Error(`${s.name}: unknown gender ${JSON.stringify(s.gender)}`);
	const [type1, type2] = s.types;
	const types = `[Some(Type::${typeVariant(type1)}), ${type2 ? `Some(Type::${typeVariant(type2)})` : 'None'}]`;
	const baseStats = STAT_ORDER.map(k => s.baseStats[k]).join(', ');

	return `    SpeciesData {
        name: "${s.name}",
        types: ${types},
        base_stats: [${baseStats}],
        abilities: [${abilityIds.join(', ')}],
        is_mega: ${!!s.isMega},
        weight_hg: ${Math.round(s.weightkg * 10)},
        nfe: ${!!s.nfe},
        fixed_max_hp: ${s.maxHP || 0},
        gender: SpeciesGender::${GENDER[s.gender]},
        battle_only_base: ${battleOnlyBase(s, byName)},
    }, // ${s.id}`;
}

function main() {
	const abilities = ordered('abilities', poolAndCatalog('abilities'));
	const abilitiesByName = new Map(abilities.map(a => [a.name, abilities.indexOf(a) + 1]));

	const { sorted, byShowdownId, byName } = buildSpeciesIdMap();

	const rows = sorted.map(s => emitSpecies(s, abilityIdsFor(abilitiesByName, s), byName));



	const gen5ById = new Map(require(path.join(__dirname, 'out', 'vgc13', 'species.json')).map(g => [g.id, g]));
	const gen5Rows = sorted.map(s => {
		const g = gen5ById.get(s.id);
		const row = g ? { ...s, types: g.types, baseStats: g.baseStats, abilities: g.abilities, nfe: g.nfe } : s;
		return emitSpecies(row, abilityIdsFor(abilitiesByName, row), byName);
	});

	const genPool = (dirs, kind) => {
		const m = new Map();
		for (const d of dirs) {
			for (const e of require(path.join(__dirname, 'out', d, `${kind}.json`))) if (!m.has(e.id)) m.set(e.id, e);
		}
		return m;
	};
	const genRows = byId => sorted.map(s => {
		const g = byId.get(s.id);
		const row = g ? { ...s, types: g.types, baseStats: g.baseStats, abilities: g.abilities, nfe: g.nfe } : s;
		return emitSpecies(row, abilityIdsFor(abilitiesByName, row), byName);
	});
	const gen6Rows = genRows(genPool(['vgc16', 'vgc15', 'vgc14'], 'species'));

	const gen7Rows = genRows(genPool(['vgc19', 'vgc18', 'vgc17'], 'species'));


	const gen9PredlcRows = genRows(genPool(['svd', 'svc'], 'species'));

	const gen8Rows = genRows(genPool(['vgc22', 'vgc21', 'vgc20'], 'species'));
	const idConsts = sorted.map(s => `    pub const ${s.id.toUpperCase()}: SpeciesId = ${byShowdownId.get(s.id)};`);

	const rust = `//! Generated by tools/gen-data/codegen-species.js from tools/gen-data/out/species.json.
//! DO NOT EDIT BY HAND. Regenerate after any Showdown pin bump (SHOWDOWN_PIN.md) or legal-pool
//! change. See that script's header comment for scope (base stats/types/abilities only - no
//! prevo/evos/movesets).

use crate::abilities_table::AbilityId;
use crate::type_chart::Type;

pub type SpeciesId = u16;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct SpeciesData {
    pub name: &'static str,
    pub types: [Option<Type>; 2],
    /// \`[hp, atk, def, spa, spd, spe]\`.
    pub base_stats: [u16; 6],
    /// Ability id per slot \`[0, 1, H, S]\`; \`0\` (NONE_ID) if that slot doesn't exist for this
    /// species. *Which* slot a given battle mon actually has is a team-building concern (M3/M4) -
    /// not resolved here. Mega forms always have exactly slot 0 populated (verified against the
    /// full legal pool) - that's the ability Mega Evolution grants (turn.rs).
    pub abilities: [AbilityId; 4],
    pub is_mega: bool,
    /// Weight in hectograms (kg x 10), for Low Kick's weight-banded base power
    /// (\`turn::low_kick_base_power\`). Integer so the threshold compares are exact.
    pub weight_hg: u16,
    /// Showdown's \`species.nfe\` (not fully evolved): Eviolite's Def / SpD x1.5.
    pub nfe: bool,
    /// Showdown's \`species.maxHP\`: a max HP fixed whatever the stats (Shedinja's 1); 0 = computed.
    pub fixed_max_hp: u16,
    /// Showdown's \`species.gender\`: fixed for some species; \`Mixed\` = the set (or a random draw) decides.
    pub gender: SpeciesGender,
    /// Showdown's \`species.battleOnly\`: the forme this battle-only forme is built as (\`set.species\`); 0 = not battle-only.
    pub battle_only_base: SpeciesId,
}

/// A species' gender rule (\`species.gender\` / \`genderRatio\`, sim/dex-species.ts). The ratio itself isn't needed in
/// the engine: whoever builds a set without a gender for a \`Mixed\` species picks one (the Python env draws it by the ratio).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum SpeciesGender {
    Mixed,
    Male,
    Female,
    Genderless,
}

pub const SPECIES_COUNT: usize = ${sorted.length};

/// Fixed ids (index + 1 into \`SPECIES\`; 0 is NONE_ID). Named by Showdown id, not display name
/// (e.g. \`CHARIZARDMEGAX\`, not \`CHARIZARD_MEGA_X\`).
pub mod species_ids {
    use super::SpeciesId;
${idConsts.join('\n')}
}

pub const SPECIES: [SpeciesData; SPECIES_COUNT] = [
${rows.join('\n')}
];

pub fn get(id: SpeciesId) -> &'static SpeciesData {
    &SPECIES[(id - 1) as usize]
}

/// Gen 5's species data (the gen5 mod: base stats, types - no Fairy -, abilities and NFE), indexed like [\`SPECIES\`]: a Gen 5 battle
/// reads these (\`Rules::species\`). A species outside the VGC13 pool keeps its default row.
pub const SPECIES_GEN5: [SpeciesData; SPECIES_COUNT] = [
${gen5Rows.join('\n')}
];

/// Gen 6's species data (the gen6 mod: VGC 2014 / 2015 / 2016), indexed like [\`SPECIES\`]; the default row outside its pools.
pub const SPECIES_GEN6: [SpeciesData; SPECIES_COUNT] = [
${gen6Rows.join('\n')}
];

/// Gen 7's species data (the gen7 / gen7sm mods: VGC 2017 / 2018 / 2019), indexed like [\`SPECIES\`]; the default row outside its
/// pools.
pub const SPECIES_GEN7: [SpeciesData; SPECIES_COUNT] = [
${gen7Rows.join('\n')}
];

/// Scarlet / Violet Reg C / D's species data (the gen9predlc mod), indexed like [\`SPECIES\`]; the default row outside its pools.
/// (Reg G / I read [\`SPECIES\`]: base Gen 9's species data is the champions mod's.)
pub const SPECIES_GEN9_PREDLC: [SpeciesData; SPECIES_COUNT] = [
${gen9PredlcRows.join('\n')}
];

/// Sword / Shield's species data (the gen8 mod; VGC 2020's gen8dlc1 dex agrees on every species in its pool), indexed like
/// [\`SPECIES\`]; the default row outside the VGC 2020-2022 pools.
pub const SPECIES_GEN8: [SpeciesData; SPECIES_COUNT] = [
${gen8Rows.join('\n')}
];
`;

	fs.mkdirSync(ENGINE_DATA_SRC, { recursive: true });
	fs.writeFileSync(path.join(ENGINE_DATA_SRC, 'species_table.rs'), rust);
	console.log(`wrote ${ENGINE_DATA_SRC}\\species_table.rs (${sorted.length} species)`);
}

main();
