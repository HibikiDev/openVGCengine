'use strict';










const fs = require('fs');
const path = require('path');
const { Dex } = require('./lib/showdown');
const { buildSpeciesIdMap } = require('./lib/species-ids');

const ENGINE_DATA_SRC = path.join(__dirname, '..', '..', 'crates', 'engine-data', 'src');
const registry = kind => JSON.parse(fs.readFileSync(path.join(__dirname, 'ids', `${kind}.json`), 'utf8'));

const MAX_MOVES = {
	Flying: 'Max Airstream', Dark: 'Max Darkness', Fire: 'Max Flare', Bug: 'Max Flutterby', Water: 'Max Geyser', Ice: 'Max Hailstorm',
	Fighting: 'Max Knuckle', Electric: 'Max Lightning', Psychic: 'Max Mindstorm', Poison: 'Max Ooze', Grass: 'Max Overgrowth',
	Ghost: 'Max Phantasm', Ground: 'Max Quake', Rock: 'Max Rockfall', Fairy: 'Max Starfall', Steel: 'Max Steelspike',
	Normal: 'Max Strike', Dragon: 'Max Wyrmwind',
};

function main() {
	const dex = Dex.mod('gen8');
	const moveIds = registry('moves');
	const moveId = id => {
		const i = moveIds.indexOf(id);
		if (i < 0) throw new Error(`move ${id} has no registry id`);
		return i + 1;
	};

	for (const name of [...Object.values(MAX_MOVES), 'Max Guard']) {
		if (dex.moves.get(name).isMax !== true) throw new Error(`${name} is not a Max Move`);
	}
	const { byShowdownId } = buildSpeciesIdMap();


	const rows = moveIds.map(id => {
		const m = dex.moves.get(id);
		const power = m.exists && !m.isNonstandard && m.category !== 'Status' && !m.isMax && !m.isZ && m.maxMove ? m.maxMove.basePower : 0;
		if (power > 255) throw new Error(`${id}: Max power ${power} does not fit a u8`);
		return `    ${power}, // ${id}`;
	});
	const types = dex.types.names().filter(t => t !== 'Stellar');
	if (types.some(t => !MAX_MOVES[t])) throw new Error(`a type without its Max Move: ${types.filter(t => !MAX_MOVES[t]).join(', ')}`);
	const typeRows = types.map(t => `    (Type::${t}, ${moveId(dex.moves.get(MAX_MOVES[t]).id)}), // ${dex.moves.get(MAX_MOVES[t]).id}`);
	const cannot = dex.species.all().filter(s => s.cannotDynamax && byShowdownId.get(s.id));
	const cannotRows = cannot.map(s => `    ${byShowdownId.get(s.id)}, // ${s.id}`);

	const gmax = dex.species.all().filter(s => s.canGigantamax);
	const missing = gmax.filter(s => !byShowdownId.get(s.id));
	if (missing.length) throw new Error(`G-Max species without an engine id: ${missing.map(s => s.id).join(', ')}`);
	const gmaxRows = gmax.map(s => {
		const move = dex.moves.get(s.canGigantamax).id;
		return `    (${byShowdownId.get(s.id)}, ${moveId(move)}), // ${s.id}: ${move}`;
	});

	const rust = `//! Generated by tools/gen-data/codegen-maxmoves.js from the gen8 mod. DO NOT EDIT BY HAND.
//! Gen 8's Max Moves: each move's \`maxMove.basePower\`, each type's Max Move
//! (\`BattleActions.MAX_MOVES\`) and the species that can't Dynamax. Regenerate after a Showdown pin bump.

use crate::moves_table::{MoveId, MOVE_COUNT};
use crate::species_table::SpeciesId;
use crate::type_chart::Type;

/// Indexed like \`moves_table::MOVES\` (id - 1): the base power a damaging move's Max Move takes (\`getActiveMaxMove\`), 0 for a status
/// move (Max Guard) and for the Max / Z-Moves themselves.
pub const MAX_POWER: [u8; MOVE_COUNT] = [
${rows.join('\n')}
];

pub fn max_power(id: MoveId) -> u8 {
    MAX_POWER[(id - 1) as usize]
}

/// Each type's Max Move (\`BattleActions.MAX_MOVES\`); a status move becomes Max Guard ([\`MAX_GUARD\`]).
pub const TYPE_MAX_MOVES: &[(Type, MoveId)] = &[
${typeRows.join('\n')}
];

/// Max Guard (\`MAX_MOVES.Status\`).
pub const MAX_GUARD: MoveId = ${moveId('maxguard')};

pub fn type_max_move(t: Type) -> MoveId {
    TYPE_MAX_MOVES.iter().find(|&&(x, _)| x == t).map_or(0, |&(_, m)| m)
}

/// Whether \`id\` is a Max Move (\`isMax\`): one of the 19, or a G-Max Move ([\`is_gmax_move\`]).
pub fn is_max_move(id: MoveId) -> bool {
    id == MAX_GUARD || TYPE_MAX_MOVES.iter().any(|&(_, m)| m == id) || is_gmax_move(id)
}

/// The species with \`cannotDynamax\` (\`getDynamaxRequest\`).
pub const CANNOT_DYNAMAX: &[SpeciesId] = &[
${cannotRows.join('\n')}
];

/// Each species' G-Max Move (\`species.canGigantamax\` of the set's species - \`Pokemon#baseSpecies\`): a Gigantamax set's damaging
/// move of that type becomes it (\`getMaxMove\`).
pub const GMAX_MOVES: &[(SpeciesId, MoveId)] = &[
${gmaxRows.join('\n')}
];

pub fn gmax_move(species: SpeciesId) -> Option<MoveId> {
    GMAX_MOVES.iter().find(|&&(s, _)| s == species).map(|&(_, m)| m)
}

/// Whether \`id\` is a G-Max Move (\`isMax\` names a species).
pub fn is_gmax_move(id: MoveId) -> bool {
    GMAX_MOVES.iter().any(|&(_, m)| m == id)
}
`;
	fs.writeFileSync(path.join(ENGINE_DATA_SRC, 'max_table.rs'), rust);
	console.log(`wrote max_table.rs: ${rows.filter(r => !/^\s+0,/.test(r)).length} moves with a Max power, ${cannot.length} species that can't Dynamax, ${gmax.length} G-Max species`);
}

main();
